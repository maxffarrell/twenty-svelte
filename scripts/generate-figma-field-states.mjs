import fs from 'node:fs';
const audit = JSON.parse(fs.readFileSync(new URL('../docs/figma-resolved-field-audit.json', import.meta.url)));
const flat = node => [node, ...node.children.filter(child => child.visible).flatMap(flat)];
const color = value => {
 if (!value) return 'transparent';
 const [hex, alpha] = value.split('/');
 return Number(alpha) === 1 ? hex : `rgb(${[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16)).join(' ')} / ${Number(alpha)*100}%)`;
};
const themed = (node, property='fill') => {
 const light=node.colors.light[property].value, dark=node.colors.dark[property].value;
 return light===dark ? color(light) : `light-dark(${color(light)}, ${color(dark)})`;
};
const input = state => audit.input.find(node=>node.name===`State=${state}, Size=Default (32px)`);
const inputSurface = state => flat(input(state)).find(node=>node.name.includes('Inputs/.Subcomponents/Input'));
const inputText = state => flat(inputSurface(state)).find(node=>node.type==='TEXT');
const inputIcon = state => flat(inputSurface(state)).find(node=>node.type==='VECTOR');
const textarea = state => audit.textarea.find(node=>node.name===`State=${state}`);
const textareaSurface = state => textarea(state).children.find(node=>node.name==='Textarea');
const cardNode = name => flat(audit.card).find(node=>node.name===name);
const iconAction = state => audit.actionVariants.find(node=>node.name===`state=${state}, size=24px, color=tertiary`);
let css='/* Generated from docs/figma-resolved-field-audit.json. Both source palette modes. */\n@layer components {\n';
const rule=(selector,body)=>{ css+=`  ${selector} { ${body} }\n`; };
rule(':where(.light, .dark)', `--tw-text: ${themed(inputText('Default'))}; --tw-secondary-text: ${themed(inputText('Disabled'))}; --tw-label: ${themed(inputText('Placeholder'))}; --tw-surface: ${themed(inputSurface('Default'))}; --tw-border: ${themed(inputSurface('Default'),'stroke')}; --tw-blue: ${themed(inputSurface('Active'),'stroke')}; --tw-danger-border: ${themed(inputSurface('Danger'),'stroke')}; --tw-textarea-danger-border: ${themed(textareaSurface('🔴 Error'),'stroke')};`);
rule('.tw-input-shell', `color: ${themed(inputIcon('Default'),'stroke')};`);
rule('.tw-input-shell:has(.tw-input:placeholder-shown)', `color: ${themed(inputIcon('Placeholder'),'stroke')};`);
rule('.tw-input-shell:focus-within', `color: ${themed(inputIcon('Active'),'stroke')};`);
rule('.tw-input-shell[data-invalid="true"]', `color: ${themed(inputIcon('Danger'),'stroke')};`);
rule('.tw-input:disabled, .tw-input:disabled::placeholder', `color: ${themed(inputText('Disabled'))};`);
rule('.tw-input-shell:has(.tw-input:disabled)', `color: ${themed(inputIcon('Disabled'),'stroke')};`);
rule('.tw-input::selection, .tw-textarea::selection', `background-color: ${themed(flat(input('Active')).find(node=>node.name==='Text Background Container'))}; color: var(--tw-text);`);
rule('.tw-card', `box-shadow: inset 0 -1px 0 ${themed(audit.card,'stroke')};`);
rule('.tw-card-description', `color: ${themed(cardNode('small card subtitle'))};`);
rule('.tw-card-avatar', `background-color: ${themed(cardNode('Icon/Round avatar'))}; color: ${themed(cardNode('L'))};`);
rule('.tw-card-action', `color: ${themed(flat(audit.card).find(node=>node.type==='VECTOR'),'stroke')}; outline: none; transition: background-color 100ms ease-out, color 100ms ease-out, box-shadow 100ms ease-out;`);
rule('.tw-card-action:hover:not(:disabled)', `background-color: ${themed(iconAction('hover'))};`);
rule('.tw-card-action:focus-visible:not(:disabled)', `background-color: ${themed(iconAction('focused'))}; box-shadow: inset 0 0 0 1px ${themed(iconAction('focused'),'stroke')};`);
rule('.tw-card-action:active:not(:disabled)', `background-color: ${themed(iconAction('pressed'))}; box-shadow: none;`);
rule('.tw-card-action[aria-pressed="true"]:not(:disabled)', `color: ${themed(flat(iconAction('active')).find(node=>node.type==='VECTOR'),'stroke')};`);
rule('.tw-card-action:disabled', `color: ${themed(flat(iconAction('disabled')).find(node=>node.type==='VECTOR'),'stroke')}; cursor: not-allowed; transition: none;`);
rule('.tw-card-action[aria-busy="true"] > *', 'visibility: hidden;');
css+='  @media (prefers-reduced-motion: reduce) { .tw-card-action { transition: none; } }\n}\n';
const target=new URL('../src/lib/figma-field-states.css',import.meta.url);
const changed=!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==css;
fs.writeFileSync(target,css);
console.log(`Resolved field/card states: ${changed?'updated stylesheet':'stylesheet already matches'}.`);
